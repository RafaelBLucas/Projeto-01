let opcao = Number(prompt("Digite uma opção"));

switch (opcao) {

    case 1:
        alert("Você escolheu a opção um");
        break;

    case 2:
        alert("Você escolheu a opção dois");
        break
     
    case 3:
        alert("Você escolheu a opção três");
        break
        
    default:
        alert("Opção inválida!!");
}